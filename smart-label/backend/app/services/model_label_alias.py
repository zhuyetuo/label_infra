"""模型输出的类别名 → 现在标签模板里的名字。

## 为什么需要这张表

预标注写库时是**按名字**找标签的（display_name，退一步 code），对不上就把那一段
丢掉，只在跑的时候弹一句提示。而模型那边的类别名是**训练时那张重映射表**定的，
跟标注模板各改各的，早就分叉了：

    模型输出   活动 / 睡觉 / 抓挠 / 未佩戴
    模板里有   活动 / 静止-休息（子级：睡眠）/ 抓挠 / 未佩戴
                     ↑ 「睡觉」这个名字模板里根本没有

后果实测（2026-09-23，任务 #45715 那一屏）：狗睡了 58.9 分钟，模型整段报「睡觉」，
**一段都没写进去**——工作台上就是一个 58.9 分钟的「未预测片段」，看起来像模型
罢工了。人当时没看到那句提示，事后更无从查起。

## 为什么是别名而不是改模板

模板名是给人看的（「静止/休息」比「睡觉」诚实：IMU 只能说它没动，说不了它睡着了），
模型类别名是训练管线的历史包袱。两边各自都有道理，中间放一张表最省事，
也最容易看出"谁跟谁是一回事"。

## 加新条目之前

先确认右边那个名字**现在的模板里真的有**——写错了不会报错，只会继续悄悄丢。
tests/test_model_label_alias.py 里有一条守着这件事。
"""

#: 模型/老数据里的类别名 → 现在模板里的显示名。
#: **只在按 display_name 和 code 都找不到时才用**，真标签永远优先。
ALIASES: dict[str, str] = {
    # 模型的「睡觉」是那个"没在动"的类。模板把它拆成了「静止/休息」和它的子级
    # 「睡眠」——映射到父级：IMU 能说的是"它没动"，说不了"它睡着了"
    "睡觉": "静止/休息",
    # 下面几个是老模板的名字，端侧模型和老数据里还在用
    "甩身体": "甩头/抖身",
    "舔身体": "舔",
    "啃身体": "啃",
    "蹭擦身体": "蹭",
    "项圈松动": "颈圈松动",
}


def resolve(name: str, by_name: dict[str, int]) -> int | None:
    """这个类别名对应项目里的哪个标签 id。找不到 None（调用方照旧记进 unmatched）。

    先按原名找，找不到再查别名——**真标签永远优先**：万一哪天模板里真加了
    一个叫「睡觉」的标签，那它说了算，不该被这张表劫走。
    """
    hit = by_name.get(name)
    if hit is not None:
        return hit
    alias = ALIASES.get(name)
    return by_name.get(alias) if alias else None
